// Rust の wgstack (crates/wgft-wgstack) は、移行の間この package と同じ入力に同じ packet を返す
// (docs/design/v2/wgstack-rs.md の「bit の一致の条件」)。TestRustGolden は、その条件のうち部品の単位で照らせる値
// (SipHash、ChaCha8 の列と種の配分、TCP の header と option の組み立て)をこの package のコードで作り、
// Rust の試験が読む golden のファイルと照らす。FuzzParse の種も Rust の parse の fuzz の target の corpus に書き出す。
// 作り直すときは -update-rust-golden を付ける。
var updateRustGolden = flag.Bool("update-rust-golden", false, "rewrite the golden values and fuzz seeds of crates/wgft-wgstack")

var rustCrate = filepath.Join("..", "..", "crates", "wgft-wgstack")

func TestRustGolden(t *testing.T) {
	var b strings.Builder
	b.WriteString("# Values from the frozen Go wgstack that the Rust wgstack must reproduce bit for bit.\n")
	b.WriteString("# Generated by: go test ./internal/wgstack -run TestRustGolden -update-rust-golden\n")
	writeSipGolden(&b)
	writeChaChaGolden(t, &b)
	writeTCPGolden(&b)
	compareOrUpdate(t, filepath.Join(rustCrate, "testdata", "go-golden.txt"), []byte(b.String()), true)
	for i, seed := range fuzzParseSeeds() {
		compareOrUpdate(t, filepath.Join(rustCrate, "fuzz", "corpus", "parse", fmt.Sprintf("go-seed-%d", i)), seed, false)
	}
}

func compareOrUpdate(t *testing.T, path string, want []byte, text bool) {
	t.Helper()
	if *updateRustGolden {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v; run with -update-rust-golden", err)
	}
	if text {
		// Windows の checkout は改行を CRLF にしうる
		got = bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n"))
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date; run go test ./internal/wgstack -run TestRustGolden -update-rust-golden", path)
	}
}

func writeSipGolden(b *strings.Builder) {
	r := rand.New(rand.NewPCG(1, 2))
	keys := []sipKey{{0, 0}, {1, 2}, {0x0706050403020100, 0x0f0e0d0c0b0a0908}, {^uint64(0), ^uint64(0)}}
	for range 4 {
		keys = append(keys, sipKey{r.Uint64(), r.Uint64()})
	}
	for _, k := range keys {
		msgs := [][2]uint64{{0, 0}, {0x0706050403020100, 0x0f0e0d0c0b0a0908}, {^uint64(0), 1}}
		for range 4 {
			msgs = append(msgs, [2]uint64{r.Uint64(), r.Uint64()})
		}
		for _, m := range msgs {
			fmt.Fprintf(b, "siphash %016x %016x %016x %016x %016x\n", k.k0, k.k1, m[0], m[1], k.sum(m[0], m[1]))
		}
		for range 4 {
			tup := tuple{laddr: r.Uint32(), raddr: r.Uint32(), lport: uint16(r.Uint32()), rport: uint16(r.Uint32())}
			fmt.Fprintf(b, "tuplehash %016x %016x %08x %08x %d %d %016x\n", k.k0, k.k1, tup.laddr, tup.raddr, tup.lport, tup.rport, k.hashTuple(tup))
		}
	}
}

func writeChaChaGolden(t *testing.T, b *strings.Builder) {
	r := rand.New(rand.NewPCG(3, 4))
	var seeds [][32]byte
	var zero, count, random [32]byte
	for i := range count {
		count[i] = byte(i)
		random[i] = byte(r.Uint32())
	}
	seeds = append(seeds, zero, count, random)
	// 種を作り直す境目 (124 個目) を 2 回越える数を出す
	for _, seed := range seeds {
		c := rand.NewChaCha8(seed)
		fmt.Fprintf(b, "chacha8 %x", seed)
		for range 300 {
			fmt.Fprintf(b, " %016x", c.Uint64())
		}
		b.WriteString("\n")
	}
	// 64 byte の種の配分。newStack が読む鍵と IP の ID と、その後の randomU64N の値
	for i := range 3 {
		var seed [64]byte
		for j := range seed {
			switch i {
			case 0:
				seed[j] = 7 // seededRand と同じ
			case 1:
				seed[j] = byte(j)
			default:
				seed[j] = byte(r.Uint32())
			}
		}
		d, err := newDevice(Config{Addr: dutAddr, MTU: testMTU, Clock: NewManualClock(), Rand: bytes.NewReader(seed[:])}, smallLimits(), newBoostPool(boostSlots))
		if err != nil {
			t.Fatal(err)
		}
		s := d.s
		fmt.Fprintf(b, "seeds %x %016x %016x %016x %016x %016x %016x %08x", seed, s.isnKey.k0, s.isnKey.k1, s.connIdx.key.k0, s.connIdx.key.k1, s.tsKey.k0, s.tsKey.k1, s.ipID.Load())
		for _, n := range []uint64{1 << 62, 3, 1000, 1<<63 + 5, 1} {
			fmt.Fprintf(b, " %d:%d", n, s.randomU64N(n))
		}
		b.WriteString("\n")
		d.Close()
	}
}

// goldenSegs は組み立てを照らす segment。buildPeer の option の順 (MSS、SACK-perm、TS、窓の scale、SACK) で書く。
var goldenSegs = []tseg{
	{sport: 1234, dport: 80, seq: 1, ack: 2, flags: flagSYN | flagACK, wnd: 999, mss: 1380, ws: 7, sackOK: true, ts: true, tsVal: 11, tsEcr: 12, payload: []byte("abc")},
	{sport: 1, dport: 2, flags: flagSYN, mss: 1380, ws: 7, sackOK: true, ts: true},
	{sport: 1, dport: 2, flags: flagACK, ws: -1, sack: []sackBlock{{1, 2}, {3, 4}}},
	{sport: 65535, dport: 443, seq: 0xfffffff0, ack: 0x80000000, flags: flagACK | flagPSH, wnd: 65535, ws: -1, ts: true, tsVal: 0xdeadbeef, tsEcr: 1, sack: []sackBlock{{5, 6}, {7, 8}, {9, 10}, {11, 12}}, payload: bytes.Repeat([]byte{0xff}, 33)},
	{sport: 40000, dport: 22, seq: 7, flags: flagFIN | flagACK, wnd: 1, ws: -1, sack: []sackBlock{{1, 2}, {3, 4}, {5, 6}, {7, 8}}, payload: []byte{0}},
	{src: netip.MustParseAddr("192.0.2.200"), sport: 9, dport: 9, flags: flagRST, ws: -1},
	{sport: 5, dport: 6, flags: flagSYN, mss: 536, ws: 14},
}

func writeTCPGolden(b *strings.Builder) {
	for _, s := range goldenSegs {
		src := s.src
		if !src.IsValid() {
			src = peerAddr
		}
		sack := "-"
		if len(s.sack) > 0 {
			var parts []string
			for _, x := range s.sack {
				parts = append(parts, fmt.Sprintf("%d-%d", x.left, x.right))
			}
			sack = strings.Join(parts, ",")
		}
		payload := "-"
		if len(s.payload) > 0 {
			payload = hex.EncodeToString(s.payload)
		}
		fmt.Fprintf(b, "tcpbuild %08x %08x %d %d %d %d %d %d %d %d %t %t %d %d %s %s %x\n",
			addrBits(src), addrBits(dutAddr), s.sport, s.dport, s.seq, s.ack, s.flags, s.wnd, s.mss, s.ws, s.sackOK, s.ts, s.tsVal, s.tsEcr, sack, payload, buildPeer(s))
	}
	// buildPeer の使わない option の書き方:SYN-ACK の SACK-perm と TS の並び、入りきらない SACK の block
	var o optWriter
	o.mss(1460)
	o.sackPermWithTS(1, 2)
	o.wscale(7)
	o.pad()
	fmt.Fprintf(b, "opts mss:1460,spts:1:2,ws:7 0 %x\n", o.b[:o.n])
	o = optWriter{}
	o.ts(3, 4)
	n := o.sack([]sackBlock{{1, 2}, {3, 4}, {5, 6}, {7, 8}})
	o.pad()
	fmt.Fprintf(b, "opts ts:3:4,sack4 %d %x\n", n, o.b[:o.n])
	// 断片の欄を書き直した IPv4 の header
	h := make([]byte, ipHeaderLen)
	writeIPv4Header(h, 1500, 0x1234, protoUDP, 0x0a090001, 0x0a090002)
	fmt.Fprintf(b, "ipv4 %x", h)
	clearDF(h)
	fmt.Fprintf(b, " %x", h)
	setFragField(h, 0x2000|185)
	fmt.Fprintf(b, " %x\n", h)
}

// fuzzParseSeeds は FuzzParse が f.Add で渡す値。
func fuzzParseSeeds() [][]byte {
	return [][]byte{
		buildPeer(tseg{sport: 1, dport: 2, flags: flagSYN, mss: 1380, ws: 7, sackOK: true, ts: true}),
		buildPeer(tseg{sport: 1, dport: 2, flags: flagACK, ws: -1, sack: []sackBlock{{1, 2}, {3, 4}}}),
	}
}
